import { test } from 'node:test'
import assert from 'node:assert/strict'
import { assemblePage, generatedComment, pageState, sha256 } from '../src/page.mjs'

const parts = { comment: generatedComment('https://github.com/Net-Logic/x/blob/v1/wiki/fr.md'), header: 'HEADER', body: 'BODY\n\n' }

test('the comment names the source and warns against manual edits', () => {
  assert.match(parts.comment, /^<!-- Generated by wiki-sync from https:\/\/github\.com\/Net-Logic\/x\/blob\/v1\/wiki\/fr\.md\./)
  assert.match(parts.comment, /Do not edit this page on the wiki/)
  assert.match(generatedComment(null), /wiki\/fr\.md of the module repository/)
})

test('the page ends with the marker of the text above it, without trailing whitespace', () => {
  const page = assemblePage(parts)
  const text = `${parts.comment}\nHEADER\n\nBODY`
  assert.equal(page, `${text}\n\n<!-- wiki-sync: sha256=${sha256(text)} -->`)
})

test('the page is NFC normalized (the wiki stores NFC)', () => {
  const page = assemblePage({ ...parts, body: 'é' })
  assert.ok(page.includes('é'))
  assert.ok(!page.includes('é'))
})

test('page states', () => {
  const page = assemblePage(parts)
  assert.equal(pageState({ exists: false }), 'missing')
  assert.equal(pageState({ exists: true, content: page }), 'synced')
  assert.equal(pageState({ exists: true, content: 'hand written' }), 'unmarked')
  assert.equal(pageState({ exists: true, content: page.replace('BODY', 'BODY edited') }), 'edited')
})

test('a page without header has the body right after the comment', () => {
  const page = assemblePage({ comment: '<!-- c -->', header: '', body: 'BODY' })
  assert.equal(page, `<!-- c -->\nBODY\n\n<!-- wiki-sync: sha256=${sha256('<!-- c -->\nBODY')} -->`)
})
