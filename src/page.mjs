import { createHash } from 'node:crypto'

const MARKER = /\n\n<!-- wiki-sync: sha256=([0-9a-f]{64}) -->$/

export function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex')
}

export function generatedComment(sourceUrl) {
  const where = sourceUrl ?? 'wiki/fr.md of the module repository'
  return `<!-- Generated by wiki-sync from ${where}.\n     Do not edit this page on the wiki: edit the repository, manual changes are refused at the next release. -->`
}

// The wiki stores NFC text without trailing whitespace: build it that way so the saved page reads back identical
export function assemblePage({ comment, header, body }) {
  const top = header ? `${comment}\n${header}\n\n` : `${comment}\n`
  const text = `${top}${body}`.normalize('NFC').replace(/\s+$/, '')
  return `${text}\n\n<!-- wiki-sync: sha256=${sha256(text)} -->`
}

// missing: no page; synced: as wiki-sync left it; unmarked: never synced; edited: changed by hand after a sync
export function pageState(current) {
  if (!current.exists) {
    return 'missing'
  }
  const match = MARKER.exec(current.content)
  if (!match) {
    return 'unmarked'
  }
  return sha256(current.content.slice(0, match.index)) === match[1] ? 'synced' : 'edited'
}
